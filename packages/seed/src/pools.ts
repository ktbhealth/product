/**
 * Locale-aware string pools for `@ktb/seed`. Pure data — the generator
 * picks from these by field-name heuristics (see generate.ts).
 *
 * `pt-BR` is the primary locale (KTB Health is a Brazilian health
 * product); `en` is the fallback for unknown locales. Pools are
 * deliberately small and hand-maintained — enough variety for demo /
 * eval data without shipping a faker dependency.
 */

export interface LocalePools {
	/** Given names (pt-BR: include accented forms). */
	readonly firstNames: readonly string[];
	/** Family names / surnames. */
	readonly lastNames: readonly string[];
	/** Street names without the thoroughfare type. */
	readonly streets: readonly string[];
	readonly neighborhoods: readonly string[];
	readonly cities: readonly string[];
	/** Region codes — pt-BR uses IBGE UF codes, en uses state names. */
	readonly states: readonly string[];
	readonly countryCode: string;
	readonly countryName: string;
	readonly emailDomains: readonly string[];
	/** Filler words for generic strings and length padding. */
	readonly words: readonly string[];
	/** BCP-47 tag emitted for language-ish keys. */
	readonly localeTag: string;
	/** Phone rendering style. */
	readonly phoneStyle: "br" | "us";
}

