/**
 * Resolve locale pools: exact tag → base language → `en` fallback.
 * Unknown/undefined locales get the English pools.
 */
export const poolsFor = (locale?: string): LocalePools => {
	if (!locale) return EN;
	const exact = LOCALES[locale];
	if (exact) return exact;
	const base = LOCALES[locale.split("-")[0]];
	return base ?? EN;
};
