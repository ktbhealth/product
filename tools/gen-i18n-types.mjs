#!/usr/bin/env bun
/**
 * gen:i18n-types — emits typed t() contracts from the generated
 * manifest (PL-008 Phase 1). The DB holds runtime values; THIS file is
 * the compile-time contract: closed key union + per-key param shapes.
 * CI regenerates and diffs — drift fails the build.
 *
 *   packages/i18n/src/types.gen.ts   (generated; never hand-edit)
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { I18N_MANIFEST } from "../packages/i18n/src/manifest.gen.ts";

const root = fileURLToPath(new URL("..", import.meta.url));
const outPath = `${root}/packages/i18n/src/types.gen.ts`;

const paramTs = (p) => {
	if (p.plural) return "number";
	if (p.cases) return "string";
	switch (p.hint) {
		case "number":
			return "number";
		case "date":
		case "datetime":
		case "relative":
			return "Date | string | number";
		case "list":
			return "readonly unknown[]";
		default:
			return "unknown";
	}
};

const entries = [];
for (const [namespace, keys] of Object.entries(I18N_MANIFEST)) {
	for (const [key, def] of Object.entries(keys)) {
		entries.push({ key: `${namespace}.${key}`, params: def.params });
	}
}
entries.sort((a, b) => a.key.localeCompare(b.key));

const keyUnion = entries.map((e) => JSON.stringify(e.key)).join(" | ");

const overloads = entries
	.map((e) => {
		if (e.params.length === 0) {
			return `\t(key: ${JSON.stringify(e.key)}): Effect.Effect<string>;`;
		}
		const fields = e.params
			.map((p) => `\t\t\t${JSON.stringify(p.name)}: ${paramTs(p)};`)
			.join("\n");
		return `\t(key: ${JSON.stringify(e.key)}, params: {\n${fields}\n\t\t}): Effect.Effect<string>;`;
	})
	.join("\n");

const body = `// Generated by tools/gen-i18n-types.mjs — do not edit.
// Regenerate: bun run gen:i18n-types
import type { Effect } from "effect";

/** Closed union of every known i18n key ("namespace.key"). */
export type I18nKey = ${keyUnion};

/** Per-key parameter shapes — the compile-time half of the contract. */
export interface I18nTypedT {
${overloads}
	/** Fallback for keys added to the manifest after this file was
	 * generated (CI drift check should prevent this). */
	(key: I18nKey, params?: Record<string, unknown>): Effect.Effect<string>;
}
`;

writeFileSync(outPath, body);
console.log(`gen-i18n-types: ${entries.length} keys → ${outPath}`);
